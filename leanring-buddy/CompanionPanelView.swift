import AVFoundation
import SwiftUI

struct CompanionPanelView: View {
    @ObservedObject var companionManager: CompanionManager
    @State private var emailInput: String = ""

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            panelHeader
            Divider()
                .background(DS.Colors.borderSubtle)
                .padding(.horizontal, 16)

            permissionsCopySection
                .padding(.top, 16)
                .padding(.horizontal, 16)

            if companionManager.lastErrorMessage != nil {
                Spacer()
                    .frame(height: 12)

                failureNoticeSection
                    .padding(.horizontal, 16)
            }

            if companionManager.lastActionDescription != nil {
                Spacer()
                    .frame(height: 12)

                lastActionSection
                    .padding(.horizontal, 16)
            }

            if companionManager.hasCompletedOnboarding && companionManager.allPermissionsGranted {
                Spacer()
                    .frame(height: 12)

                visionModelSummaryRow
                    .padding(.horizontal, 16)
            }

            if !companionManager.allPermissionsGranted {
                Spacer()
                    .frame(height: 16)

                settingsSection
                    .padding(.horizontal, 16)
            }

            if !companionManager.hasCompletedOnboarding && companionManager.allPermissionsGranted {
                Spacer()
                    .frame(height: 16)

                startButton
                    .padding(.horizontal, 16)
            }

            // Whether the blue cursor is on screen is 通用 → 「蓝色光标」 in the
            // settings window now. The toggle that used to live here was commented
            // out, which is what left the app with no way to hide the cursor at all.

            if companionManager.hasCompletedOnboarding && companionManager.allPermissionsGranted {
